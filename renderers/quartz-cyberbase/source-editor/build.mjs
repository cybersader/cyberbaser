// Rebuild offline after `npm ci --ignore-scripts --offline` in this directory.
// Default verifies committed bytes; --write intentionally updates the vendored asset and browser pointer.
import fs from "node:fs"
import path from "node:path"
import { fileURLToPath } from "node:url"
import { createHash } from "node:crypto"
import { gzipSync } from "node:zlib"
const here = path.dirname(fileURLToPath(import.meta.url))
const renderer = path.dirname(here)
if (typeof Bun === "undefined" || Bun.version !== "1.3.14") throw Error("Reproducible source-editor builds require Bun 1.3.14.")
const lock = JSON.parse(fs.readFileSync(path.join(here, "package-lock.json"), "utf8"))
for (const [location, pkg] of Object.entries(lock.packages)) {
  if (!location) continue
  const installed = JSON.parse(fs.readFileSync(path.join(here, location, "package.json"), "utf8"))
  if (installed.version !== pkg.version) throw Error(`Installed dependency differs from lock: ${location}`)
}
const result = await Bun.build({
  entrypoints: [path.join(here, "src/index.ts")], target: "browser", format: "iife",
  minify: true, sourcemap: "none", splitting: false,
})
if (!result.success) throw new AggregateError(result.logs, "Source editor bundle failed")
const notices = `Cyberbaser adapter: AGPL-3.0-only. Corresponding source:\nhttps://github.com/cybersader/cyberbaser/tree/main/renderers/quartz-cyberbase/source-editor\n${fs.readFileSync(path.join(here, "LICENSES/AGPL-3.0.txt"), "utf8")}\n${fs.readFileSync(path.join(here, "LICENSES/third-party-notices.txt"), "utf8")}`
const bytes = Buffer.from(`/*! Cyberbaser source editor. Third-party notices:\n${notices.replaceAll("*/", "* /")}\n*/\n${await result.outputs[0].text()}`)
const digest = createHash("sha256").update(bytes).digest("hex")
const filename = `source-editor.${digest.slice(0, 16)}.js`
const target = path.join(renderer, "vendor", filename)
if (process.argv.includes("--write")) {
  fs.mkdirSync(path.dirname(target), { recursive: true })
  for (const file of fs.readdirSync(path.dirname(target))) if (/^source-editor\.[a-f0-9]{16}\.js(?:\.sha256)?$/u.test(file)) fs.unlinkSync(path.join(path.dirname(target), file))
  fs.writeFileSync(target, bytes)
  fs.writeFileSync(`${target}.sha256`, `${digest}  ${filename}\n`)
  fs.writeFileSync(path.join(renderer, "components/sourceEditorAsset.ts"), `// Generated by source-editor/build.mjs --write; no editor code enters the page bundle.\nexport const sourceEditorAsset = ${JSON.stringify(filename)}\n`)
} else {
  if (!fs.existsSync(target) || !fs.readFileSync(target).equals(bytes) || fs.readFileSync(`${target}.sha256`, "utf8") !== `${digest}  ${filename}\n`) throw Error("Source editor rebuild differs from committed asset. Review and rebuild with --write.")
}
console.log(`source-editor bundle: ${filename}; ${bytes.length} bytes raw; ${gzipSync(bytes, { level: 9 }).length} bytes gzip; SHA-256 ${digest}; ${process.argv.includes("--write") ? "written" : "byte-identical"}`)
