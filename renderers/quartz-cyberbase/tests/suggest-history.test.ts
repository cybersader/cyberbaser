import assert from "node:assert/strict"
import { SuggestHistory, changeContext } from "../components/suggestModeHistory"
import { SparseRun, sortedOperations } from "../components/suggestModeModel"
const history = new SuggestHistory<string>()
history.record("", "a", { group: "one", start: "r:0", end: "r:1" }, 0)
history.record("a", "ab", { group: "one", start: "r:1", end: "r:2" }, 1000)
assert.equal(history.undo(), "")
assert.equal(history.redo(), "ab")
history.record("ab", "abc", { group: "one", start: "r:2", end: "r:3" }, 1001)
history.record("abc", "abcd", { group: "one", start: "r:3", end: "r:4" }, 2002)
assert.equal(history.undo(), "abc", "a pause over one second breaks typing")
assert.equal(history.undo(), "ab", "redo does not coalesce with new typing")
history.clear()
history.record("", "a", { group: "one", start: "r:0", end: "r:1" }, 0)
history.record("a", "ba", { group: "one", start: "r:0", end: "r:1" }, 1)
assert.equal(history.undo(), "a", "a caret jump breaks typing")
history.record("a", "ac", { group: "two", start: "r:1", end: "r:2" }, 2)
assert.equal(history.canRedo, false)
assert.equal(history.undo(), "a", "a block change breaks typing")
history.clear()
history.record("", "a", { group: "one", start: "r:0", end: "r:1" }, 0)
history.breakGroup()
history.record("a", "ab", { group: "one", start: "r:1", end: "r:2" }, 1)
assert.equal(history.undo(), "a", "moving away and back breaks typing")
history.clear()
for (let i = 0; i < 105; i++) history.record(String(i), String(i + 1))
for (let i = 0; i < 100; i++) assert.notEqual(history.undo(), undefined)
assert.equal(history.canUndo, false, "bounded to 100 snapshots")
// History snapshots restore only the existing ledger. CRLF, Unicode and original
// byte identities remain governed by SparseRun rather than history machinery.
const run = new SparseRun("fixture", 11, "Before 😀\r\nAfter")
const ledger = new SuggestHistory<ReturnType<typeof sortedOperations>>()
const before = sortedOperations([run])
run.replace(7, 9, "🌍")
ledger.record(before, sortedOperations([run]))
run.restore(ledger.undo()!)
assert.equal(run.currentText, "Before 😀\r\nAfter")
run.restore(ledger.redo()!)
assert.deepEqual(run.operations(), [{ operationId: "edit-fixture-18", start: 18, end: 22, expected: "😀", replacement: "🌍" }])
const text = "prefix ".repeat(20) + "CHANGED" + " suffix".repeat(20)
const context = changeContext(text, 140, 147)
assert.ok(context.before.startsWith("…") && context.after.endsWith("…"))
assert.ok(context.before.length <= 61 && context.after.length <= 61)
assert.equal(changeContext("short sentence", 6, 14).before, "short ")
console.log("suggest-history: deterministic history/coalescing/caret/pause/cap/context assertions and exact CRLF/emoji ledger restore passed")
